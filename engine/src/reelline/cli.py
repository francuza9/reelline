"""The `reelline` command (engine/pyproject.toml [project.scripts]).

reelline config show [--channel DIR] [--set section.key=value ...]
    the merged config as YAML (every layer applied); credential values never appear (the config
    only names their variables), and any key that looks like one is masked anyway
reelline config docs
    the configuration reference (docs/configuration.md), generated from the schema
reelline config env-example [--channel DIR]
    the channel's .env.example, from the schema's credential fields and the channel's names
reelline init DIR [--name NAME]
    a new channel in DIR copied from channels/example (config, prompts, sources, a placeholder host), the
    name filled in, and its .env.example
reelline doctor [--channel DIR] [--no-secrets]
    validates the config and sources.yaml, lists the credentials missing from the env file
    (names only, never values) and the paths that don't exist; exit 1 on a problem;
    --no-secrets skips the env file and credentials (CI has none)
reelline review list [--channel DIR]
    the pending reviews (read-only) with their buttons as `reelline review tap` commands
reelline review tap <action> [--user NAME]  |  reelline review say <text> [--user NAME]
    a decision for the approval bot (a button's action data, e.g. r:12:ap; or a command such as
    /status, or a new caption), dropped in review.cli.inbox_dir; the cli, webhook and auto review
    channels take it on their next receive (reelline/review/inbox.py)
reelline run [--channel DIR] [--from STEP] [--to STEP] [--dry-run] [--slot HH:MM [--date D]]
            [--input FILE [--store FILE]]
    the chain (pipeline: in config.yaml) for one slot on the channel's database, or --from/--to
    a slice of it; a rerun goes on after the last finished pass. --input: on plain inputs
    instead (JSON, reelline/pipeline/artifacts.py), the made artifacts printed as JSON, --store
    keeping the passes. --dry-run: no review sent, nothing published
reelline step NAME [--channel DIR] (--script ID | --input FILE | --slot HH:MM [--date D])
    one step: on a stored script's story, brief, draft and script (nothing stored but the
    calls' cost), on plain inputs, or for a slot; prints what it made
reelline tick [--channel DIR]
    what the systemd timer runs (python -m reelline.pipeline.run_daily tick, which still works)
"""

from __future__ import annotations

import argparse
import re
import sys
import textwrap
from collections.abc import Callable, Iterator
from pathlib import Path
from typing import Any

import yaml
from dotenv import dotenv_values
from pydantic import BaseModel

from reelline.config import ConfigError, load_config
from reelline.config.schema import Config

_SECRETISH = re.compile(r"(token|secret|password|api_key)$")
MASK = "********"


def env_fields(config: Config) -> Iterator[tuple[str, str, str, dict]]:
    """(dotted path, the variable's name, its description, {"secret", "optional"}) for every `*_env` field."""

    def walk(model: BaseModel, prefix: str):
        for name, field in type(model).model_fields.items():
            value = getattr(model, name)
            extra = field.json_schema_extra if isinstance(field.json_schema_extra, dict) else {}
            if isinstance(value, BaseModel):
                yield from walk(value, f"{prefix}{name}.")
            elif extra.get("env"):
                yield f"{prefix}{name}", value, field.description or "", extra

    yield from walk(config, "")


def plain(value: Any, key: str = "") -> Any:
    if isinstance(value, BaseModel):
        return {
            **{k: plain(getattr(value, k), k) for k in type(value).model_fields},
            **{k: plain(v, k) for k, v in (value.__pydantic_extra__ or {}).items()},
        }
    if isinstance(value, dict):
        return {k: plain(v, str(k)) for k, v in value.items()}
    if isinstance(value, tuple | list):
        return [plain(v) for v in value]
    if isinstance(value, frozenset | set):
        return sorted(plain(v) for v in value)
    if isinstance(value, Path):
        return str(value)
    if value and isinstance(value, str) and _SECRETISH.search(key):
        return MASK
    return value


def show(config: Config) -> str:
    return yaml.safe_dump(plain(config), allow_unicode=True, sort_keys=False, width=120)


def env_example(config: Config) -> str:
    out = [
        f"# Credentials of the {config.channel.name} channel: copy to .env (next to config.yaml, or the",
        "# repo root) and fill in. Never commit real values. Generated by `reelline config env-example`",
        "# from the config's *_env fields (config.yaml names each variable). The engine reads only this",
        "# file, never the shell env, gcloud or ADC; REELLINE__STORAGE__ENV_FILE (absolute) may point to",
        "# another one. A feature fails with the missing key's name only when it runs; (optional): the",
        "# feature works, or is skipped, without it.",
    ]
    section = None
    for path, name, what, extra in env_fields(config):
        here = path.rsplit(".", 1)[0]
        if here != section:
            section = here
            out += ["", f"# --- {section} ---"]
        out += textwrap.wrap(
            f"{what}{' (optional)' if extra.get('optional') else ''}", 98, initial_indent="# ", subsequent_indent="# "
        )
        out.append(f"{name}=")
    out += [
        "",
        "# --- per-machine settings (not credentials; any REELLINE__SECTION__KEY works here) ---",
        "# Who restarts a dead approval bot: tick (default) or systemd (the server).",
        "# REELLINE__STEPS__RUN_DAILY__BOT_SUPERVISOR=systemd",
    ]
    return "\n".join(out) + "\n"


def enabled_credentials(config: Config) -> Callable[[str], bool]:
    """Whether the credentials at a config path (publish.meta.page_id_env, ...) belong to an adapter this
    config uses; doctor asks only for those. A path no rule names is always asked for."""
    targets = set(config.publish.targets.values())
    collectors = set(config.steps.analytics.collectors)
    telegram = "telegram" in (config.review.channel, config.notify.channel)
    uses = {
        "models.providers.": lambda path: path.split(".")[2] in {r.provider for r in config.models.roles().values()},
        "review.telegram.": lambda path: telegram,
        "publish.meta.": lambda path: "meta" in targets or "meta" in collectors,
        "publish.buffer.": lambda path: "buffer" in targets or "buffer" in collectors,
        "publish.r2.": lambda path: config.storage.blob.kind == "s3",
        "publish.credits_page.": lambda path: bool(config.publish.credits_page.project),
    }

    def enabled(path: str) -> bool:
        return all(rule(path) for prefix, rule in uses.items() if path.startswith(prefix))

    return enabled


def doctor(config: Config, secrets: bool = True) -> list[str]:
    """Problems, one line each (empty: all good). secrets=False skips the env file and credentials."""
    from reelline.config.credentials import resolve_env_file
    from reelline.pipeline.sources import SourceRegistryError, load_sources

    problems = []
    try:
        load_sources(config.sources)
    except SourceRegistryError as exc:
        problems.append(f"sources: {exc}")

    if secrets:
        try:
            env_file = resolve_env_file()
        except ConfigError as exc:
            problems.append(f"env file: {exc}")
            env_file = None
        values = dotenv_values(env_file, interpolate=False) if env_file and env_file.is_file() else {}
        if env_file and not env_file.is_file():
            problems.append(f"env file: {env_file} not found")
        enabled = enabled_credentials(config)
        for path, name, _, extra in env_fields(config):
            if enabled(path) and not (values.get(name) or "").strip():
                kind = "optional, " if extra.get("optional") else ""
                line = f"credential missing: {name} ({kind}{path})"
                if not extra.get("optional"):
                    problems.append(line)
                else:
                    print(line)

    # the db's directory is not checked: db.connect() creates it (a fresh clone has none)
    from reelline.pipeline.chain import ChainError, load_chain

    try:
        load_chain(config)
    except ChainError as exc:
        problems.append(f"pipeline: {exc}")

    must_exist = [("sources", config.sources), ("storage.prompts_dir", config.storage.prompts_dir)]
    for step, section in config.steps:
        for name in type(section).model_fields:
            value = getattr(section, name)
            if name.endswith("prompt") and isinstance(value, Path):
                must_exist.append((f"steps.{step}.{name}", value))
    for what, path in must_exist:
        if not path.exists():
            problems.append(f"path missing: {what}: {path}")
    return problems


def review_command(config: Config, args) -> int:
    from reelline.review import inbox

    if args.action == "list":
        import sqlite3

        from reelline.review import machine

        db_path = Path(config.storage.db_path)
        if not db_path.is_file():
            print(f"no database at {db_path}")
            return 1
        conn = sqlite3.connect(f"file:{db_path}?mode=ro", uri=True)
        conn.row_factory = sqlite3.Row
        rows = conn.execute("SELECT * FROM reviews WHERE status = 'pending' ORDER BY id").fetchall()
        for r in rows:
            pick = conn.execute("SELECT slot_date, slot_time FROM picks WHERE id = ?", (r["pick_id"],)).fetchone()
            print(f"Review #{r['id']} · reel #{r['reel_id']} · {pick['slot_date']} {pick['slot_time']} · {r['state']}")
            for row in machine.markup(conn, r):
                for label, data in row:
                    print(f"  [{label}]  reelline review tap {data}")
        print(f"{len(rows)} pending review(s)")
        return 0
    entry = {"type": "tap", "data": args.data} if args.action == "tap" else {"type": "say", "text": " ".join(args.text)}
    path = inbox.drop({**entry, "user": args.user}, Path(config.review.cli.inbox_dir))
    print(f"queued: {path}")
    if config.review.channel == "telegram":
        print("note: review.channel is telegram; only the cli, webhook and auto channels read the inbox")
    return 0


def _slot(config: Config, args) -> tuple[str, str]:
    from datetime import datetime

    from reelline.pipeline.scoring import tbilisi

    day = args.date or datetime.now(tbilisi()).date().isoformat()
    return day, args.slot or config.channel.slots[0]


def _plain(chain_steps, args, start_inputs=None) -> int:
    from reelline.pipeline.artifacts import dump, load_inputs
    from reelline.pipeline.chain import check
    from reelline.pipeline.runner import Runner
    from reelline.pipeline.step import Context, JsonFileStore, MemoryStore

    artifacts, state = load_inputs(args.input)
    check(chain_steps, available=set(artifacts))
    store = JsonFileStore(args.store) if getattr(args, "store", None) else MemoryStore()
    ctx = Context(
        artifacts=dict(artifacts),
        store=store,
        dry_run=args.dry_run,
        state=state,
        log=lambda m: print(m, file=sys.stderr, flush=True),
    )
    outcome = Runner(chain_steps).run(ctx)
    print(dump({k: v for k, v in ctx.artifacts.items() if k not in artifacts}))
    if outcome.stopped_at:
        print(f"{outcome.stopped_at}: {outcome.status}: {outcome.detail}", file=sys.stderr)
    return 1 if outcome.status == "failed" else 0


def run_command(config: Config, args) -> int:
    from reelline.pipeline import db
    from reelline.pipeline.chain import load_chain
    from reelline.pipeline.slices import run_chain

    chain = load_chain(config)
    if args.input:
        return _plain(chain.slice(args.start, args.stop), args)
    outcome = run_chain(
        db.connect(config.storage.db_path),
        *_slot(config, args),
        start=args.start,
        stop=args.stop,
        dry_run=args.dry_run,
        chain=chain,
    )
    return 1 if outcome.status == "failed" else 0


def step_command(config: Config, args) -> int:
    from reelline.pipeline import db
    from reelline.pipeline.artifacts import dump
    from reelline.pipeline.chain import load_chain
    from reelline.pipeline.runner import Runner
    from reelline.pipeline.slices import db_context

    step = load_chain(config).get(args.name)
    if args.input:
        return _plain([step], args)
    conn = db.connect(config.storage.db_path)
    if args.script is not None:
        ctx = script_context(conn, args.script, dry_run=args.dry_run)
    else:
        ctx = db_context(conn, *_slot(config, args), dry_run=args.dry_run)
    before = set(ctx.artifacts)
    outcome = Runner([step]).run(ctx)
    print(dump({k: v for k, v in ctx.artifacts.items() if k not in before}))
    if outcome.stopped_at:
        print(f"{outcome.stopped_at}: {outcome.status}: {outcome.detail}", file=sys.stderr)
    return 1 if outcome.status == "failed" else 0


def script_context(conn, script_id: int, *, dry_run: bool = False):
    """A stored script's story, brief, draft and script as a run's artifacts; its passes aren't
    touched (the store is the run's own), its pick and slot are the context's."""
    from datetime import date

    from reelline.media.script_markup import parse
    from reelline.pipeline import db
    from reelline.pipeline.script import PassResult
    from reelline.pipeline.slices import db_context
    from reelline.pipeline.step import Artifact

    row = conn.execute("SELECT * FROM scripts WHERE id = ?", (script_id,)).fetchone()
    if row is None:
        raise SystemExit(f"no script #{script_id}")
    pick = conn.execute("SELECT * FROM picks WHERE id = ?", (row["pick_id"],)).fetchone()
    brief = conn.execute("SELECT markdown FROM briefs WHERE id = ?", (row["brief_id"],)).fetchone()
    ctx = db_context(conn, pick["slot_date"], pick["slot_time"], dry_run=dry_run, pick_id=pick["id"])
    ctx.sessions.clear()
    flirt = bool(pick["flirt"])
    ctx.state.update(
        flirt=flirt,
        angle=pick["flirt_angle"],
        publish_date=date.fromisoformat(pick["slot_date"]) if pick["slot_date"] else None,
    )
    ctx.artifacts[Artifact.STORY] = db.get_story(conn, row["story_id"])
    if brief is not None:
        ctx.artifacts[Artifact.BRIEF] = brief["markdown"]
    if row["draft"]:
        ctx.artifacts[Artifact.DRAFT] = PassResult(row["draft"])
    if row["final"]:
        ctx.artifacts[Artifact.SCRIPT] = PassResult(row["final"], script=parse(row["final"], flirt=flirt))
    return ctx


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(prog="reelline")
    sub = parser.add_subparsers(dest="command", required=True)
    cfg_p = sub.add_parser("config", help="the channel's config")
    cfg_sub = cfg_p.add_subparsers(dest="action", required=True)
    doctor_p = sub.add_parser("doctor", help="validate the config, the credentials and the paths")
    doctor_p.add_argument(
        "--no-secrets", action="store_true", help="skip the env file and the credentials (CI, a fresh clone)"
    )
    review_p = sub.add_parser("review", help="pending reviews; a decision for the approval bot")
    review_sub = review_p.add_subparsers(dest="action", required=True)
    list_p = review_sub.add_parser("list", help="the pending reviews and their actions")
    tap_p = review_sub.add_parser("tap", help="press a button: its action data (r:12:ap)")
    tap_p.add_argument("data")
    say_p = review_sub.add_parser("say", help="send a command (/status) or text (a new caption)")
    say_p.add_argument("text", nargs="+")
    for p in (tap_p, say_p):
        p.add_argument("--user", default="cli")
    run_p = sub.add_parser("run", help="the chain for one slot (or a slice of it)")
    run_p.add_argument("--from", dest="start", metavar="STEP")
    run_p.add_argument("--to", dest="stop", metavar="STEP")
    run_p.add_argument("--store", type=Path, help="with --input: keep the passes in this JSON file")
    step_p = sub.add_parser("step", help="one step on a stored script, plain inputs or a slot")
    step_p.add_argument("name")
    step_p.add_argument("--script", type=int, metavar="ID")
    for p in (run_p, step_p):
        p.add_argument("--input", type=Path, metavar="FILE", help="plain inputs (JSON), no database")
        p.add_argument("--slot", metavar="HH:MM")
        p.add_argument("--date", metavar="YYYY-MM-DD")
        p.add_argument("--dry-run", action="store_true", help="no review sent, nothing published")
    tick_p = sub.add_parser("tick", help="what the systemd timer runs")
    init_p = sub.add_parser("init", help="a new channel, copied from the example channel")
    init_p.add_argument("dir", type=Path, help="the new channel's directory (empty or not there yet)")
    init_p.add_argument("--name", help="the channel's name (default: the directory's name)")
    dev_p = sub.add_parser("dev", help="developer tools")
    dev_sub = dev_p.add_subparsers(dest="action", required=True)
    leak_p = dev_sub.add_parser("leak-guard", help="scan engine/ for what must not be in the open-source tree")
    leak_p.add_argument("--root", type=Path, help="the tree to scan (default: engine/)")
    leak_p.add_argument("--allowlist", type=Path, help="the known exceptions (default: engine/leak_guard_allow.toml)")
    leak_p.add_argument("--summary", action="store_true", help="list every allowlist entry's hit count")
    cfg_sub.add_parser("docs", help="the configuration reference (Markdown), from the schema")
    for p in (
        cfg_sub.add_parser("show", help="the merged config, every layer applied"),
        cfg_sub.add_parser("env-example", help="the channel's .env.example"),
        doctor_p,
        list_p,
        tap_p,
        say_p,
        run_p,
        step_p,
        tick_p,
    ):
        p.add_argument(
            "--channel",
            type=Path,
            help="the channel directory (default: REELLINE_CHANNEL, else the one under channels/)",
        )
        p.add_argument(
            "--set",
            action="append",
            default=[],
            metavar="SECTION.KEY=VALUE",
            help="override a setting (the value is read as YAML)",
        )
    args = parser.parse_args(argv)

    if args.command == "init":  # makes the config, so none to load
        from reelline.init import scaffold

        try:
            dest = scaffold(args.dir, args.name)
        except ConfigError as exc:
            print(f"init: {exc}", file=sys.stderr)
            return 1
        print(f"{dest}: a new channel. Next: edit config.yaml, sources.yaml and prompts/; copy .env.example to .env;")
        print(f"  reelline doctor --channel {dest}")
        return 0
    if args.command == "config" and args.action == "docs":  # the schema's defaults, no channel
        from reelline.config.docs import render

        sys.stdout.write(render())
        return 0
    if args.command == "dev":  # no channel, no config
        from reelline.dev import leak_guard

        return leak_guard.main(
            args.root or leak_guard.ALLOWLIST.parent, args.allowlist or leak_guard.ALLOWLIST, args.summary
        )

    from reelline.config import set_config

    try:
        overrides = {}
        for item in args.set:
            key, sep, value = item.partition("=")
            if not sep:
                raise ConfigError(f"--set {item}: expected SECTION.KEY=VALUE")
            overrides[key] = yaml.safe_load(value)
        config = load_config(args.channel, overrides)
    except ConfigError as exc:
        print(f"config: {exc}", file=sys.stderr)
        return 1
    set_config(config)
    if args.command == "config" and args.action == "show":
        sys.stdout.write(show(config))
    elif args.command == "config":
        sys.stdout.write(env_example(config))
    elif args.command == "review":
        return review_command(config, args)
    elif args.command in ("run", "step"):
        from reelline.pipeline.chain import ChainError
        from reelline.pipeline.step import StepError

        try:
            return (run_command if args.command == "run" else step_command)(config, args)
        except (ChainError, StepError) as exc:
            print(f"{args.command}: {exc}", file=sys.stderr)
            return 1
    elif args.command == "tick":
        from reelline.pipeline import run_daily

        return run_daily.main(["tick"])
    else:
        problems = doctor(config, secrets=not args.no_secrets)
        for line in problems:
            print(line)
        print(f"{config.channel.name}: {'OK' if not problems else f'{len(problems)} problem(s)'}")
        return 1 if problems else 0
    return 0


if __name__ == "__main__":
    sys.exit(main())
